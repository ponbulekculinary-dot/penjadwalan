import {readFile, writeFile, mkdir} from 'node:fs/promises';
const awaitLockJS=await readFile(new URL('./ui/schedule-lock.js',import.meta.url),'utf8');
const cashJS=await readFile(new URL('./ui/cash.js',import.meta.url),'utf8');
let template = await readFile(new URL('./ui/index.html', import.meta.url), 'utf8');
template=template.replace('// CASH_SCRIPT',()=>cashJS);
template=template.replace('// LOCK_SCRIPT',()=>awaitLockJS);
const reviewCSS=await readFile(new URL('./ui/review.css',import.meta.url),'utf8');
const reviewJS=await readFile(new URL('./ui/review.js',import.meta.url),'utf8');
const availabilityJS=await readFile(new URL('./ui/availability.js',import.meta.url),'utf8');
template=template.replace('// AVAILABILITY_SCRIPT',()=>availabilityJS);
template=template.replace('/* REVIEW_STYLES */',()=>reviewCSS).replace('// REVIEW_SCRIPT',()=>reviewJS);
const scheduler = (await readFile(new URL('./scheduler.js', import.meta.url), 'utf8')).replace(/^export /gm, '');
const review = (await readFile(new URL('./schedule-view.js', import.meta.url), 'utf8')).replace(/^import .*;\n/gm, '').replace(/^export /gm, '');
const availability = (await readFile(new URL('./availability.js',import.meta.url),'utf8')).replace(/^import .*;\n/gm,'').replace(/^export /gm,'');
const demo = await readFile(new URL('./demo-runtime.js', import.meta.url), 'utf8');
if (!template.includes('<!-- DEMO_RUNTIME -->')) throw new Error('Demo marker missing.');
await mkdir(new URL('./public/', import.meta.url), {recursive: true});
await writeFile(new URL('./public/index.html', import.meta.url), template.replace('<!-- DEMO_RUNTIME -->', () => `<script>\n(() => {\n${scheduler}\n${availability}\n${review}\nwindow.FrameSchedule = {swapAssignments,rotateAssignments,selectedServices,normalizedServices,SERVICE_RULES};\n${demo}\n})();\n</script>`));
